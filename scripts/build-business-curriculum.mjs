// Generates the portal seed for the HTH Business Curriculum.
// Structure (courses, units, instructors) comes from scripts/data/business-curriculum.mjs.
// Full lesson text comes from scripts/data/lessons/<course>/<unit>/NN-slug.md
//   line 1: "# Lesson title"   line 3: "> one-line summary"   rest: the lesson (Markdown)
// A unit with no .md files falls back to the short outline in the data file.
//
// Usage: node scripts/build-business-curriculum.mjs            -> writes drizzle/manual/20_seed_business_curriculum.sql
//        node scripts/build-business-curriculum.mjs --json out  -> also writes the data as JSON (for the Word export)
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { courses, retired, lessonMarkdown } from "./data/business-curriculum.mjs";

const OUT = "drizzle/manual/20_seed_business_curriculum.sql";
const LESSONS = "scripts/data/lessons";
const slug = (s) => s.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const q = (s) => `'${s.replace(/'/g, "''")}'`;
const md = (s) => {
  // db:apply splits statements on a semicolon at end of line, and $md$ ends the literal.
  if (s.includes("$md$")) throw new Error(`Unsafe text for the seed: ${s.slice(0, 60)}`);
  return `$md$${s.replace(/;([ \t]*)(\r?\n|$)/g, ".$1$2")}$md$`;
};
const classId = (title) => `(SELECT "id" FROM "classes" WHERE "title" = ${q(title)} ORDER BY "id" LIMIT 1)`;
const retiredList = retired.map(q).join(", ");

function readUnit(courseTitle, index, u) {
  const dir = join(LESSONS, slug(courseTitle.replace(/ — .*/, "")), `${index + 1}-${slug(u.name)}`);
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".md")).sort() : [];
  if (files.length === 0) return u.lessons.map((l) => ({ title: l.title, summary: l.summary, markdown: lessonMarkdown(l), note: l.note }));
  return files.map((f) => {
    const text = readFileSync(join(dir, f), "utf8").replace(/\r\n?/g, "\n").trim();
    const m = text.match(/^# (.+)\n+> (.+)\n+([\s\S]+)$/);
    if (!m) throw new Error(`${join(dir, f)}: expected "# Title", then "> summary", then the lesson`);
    return { title: m[1].trim(), summary: m[2].trim(), markdown: m[3].trim() };
  });
}

const built = courses.map((c) => ({ ...c, units: c.units.map((u, i) => ({ ...u, lessons: readUnit(c.title, i, u) })) }));

let sql = `-- HTH Business Curriculum: four supplementary courses whose units are the mini courses written by
-- Brittni Hardie and Dakotah Jennifer. Generated by scripts/build-business-curriculum.mjs.
-- Courses are hidden drafts. Safe to re-run. A lesson that someone has edited in the portal is never
-- overwritten or removed (its updated_at differs from created_at). The Core Curriculum is not touched.
-- Applied by: npm run db:apply

ALTER TABLE "lessons" ADD COLUMN IF NOT EXISTS "unit" text;

-- The first version of this seed made every mini course its own course. Remove those drafts (only if nobody is enrolled).
DELETE FROM "lessons" WHERE "class_id" IN (SELECT c."id" FROM "classes" c WHERE c."title" IN (${retiredList}) AND c."is_published" = false AND NOT EXISTS (SELECT 1 FROM "enrollments" e WHERE e."class_id" = c."id"))
;
DELETE FROM "classes" c WHERE c."title" IN (${retiredList}) AND c."is_published" = false AND NOT EXISTS (SELECT 1 FROM "enrollments" e WHERE e."class_id" = c."id") AND NOT EXISTS (SELECT 1 FROM "lessons" l WHERE l."class_id" = c."id")
;
`;

for (const c of built) {
  const titles = c.units.flatMap((u) => u.lessons.map((l) => l.title));
  if (new Set(titles).size !== titles.length) throw new Error(`Duplicate lesson titles in ${c.title}`);
  sql += `
INSERT INTO "classes" ("title", "description", "teacher_id", "type", "is_published")
SELECT ${q(c.title)}, ${md(c.description)},
  COALESCE((SELECT "id" FROM "users" WHERE "name" = ${q(c.teacher)} ORDER BY "id" LIMIT 1), (SELECT "id" FROM "users" WHERE "role" = 'admin' ORDER BY "id" LIMIT 1)),
  'pre-course', false
WHERE NOT EXISTS (SELECT 1 FROM "classes" WHERE "title" = ${q(c.title)})
;
UPDATE "classes" SET "type" = 'pre-course' WHERE "id" = ${classId(c.title)} AND "is_published" = false
;
-- Unedited lessons that are no longer part of this course (merged into fuller lessons).
DELETE FROM "lessons" WHERE "class_id" = ${classId(c.title)} AND "updated_at" = "created_at" AND "title" NOT IN (${titles.map(q).join(", ")})
;
`;
  let order = 0;
  for (const u of c.units) {
    for (const l of u.lessons) {
      order++;
      sql += `
INSERT INTO "lessons" ("class_id", "unit", "title", "summary", "content", "duration_minutes", "is_published", "order")
SELECT c."id", ${q(u.name)}, ${q(l.title)}, ${md(l.summary)}, ${md(l.markdown)}, ${u.minutes ?? "NULL"}, true, ${order}
FROM "classes" c
WHERE c."id" = ${classId(c.title)}
AND NOT EXISTS (SELECT 1 FROM "lessons" l WHERE l."class_id" = c."id" AND l."title" = ${q(l.title)})
;
UPDATE "lessons" SET "unit" = ${q(u.name)}, "order" = ${order}, "summary" = ${md(l.summary)}, "content" = ${md(l.markdown)}
WHERE "class_id" = ${classId(c.title)} AND "title" = ${q(l.title)} AND "updated_at" = "created_at"
;
`;
    }
  }
}

writeFileSync(OUT, sql);
const units = built.reduce((n, c) => n + c.units.length, 0);
const words = (s) => s.split(/\s+/).filter(Boolean).length;
for (const c of built) for (const u of c.units) console.log(`${c.title} / ${u.name}: ${u.lessons.length} lessons, ${u.lessons.map((l) => words(l.markdown)).join(" ")} words`);
console.log(`${OUT}: ${built.length} courses, ${units} units, ${built.reduce((n, c) => n + c.units.reduce((m, u) => m + u.lessons.length, 0), 0)} lessons`);

const j = process.argv.indexOf("--json");
if (j > -1) writeFileSync(process.argv[j + 1], JSON.stringify({ courses: built }, null, 2));
