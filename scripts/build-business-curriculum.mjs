// Generates the portal seed for the HTH Business Curriculum from scripts/data/business-curriculum.mjs.
// Usage: node scripts/build-business-curriculum.mjs            -> writes drizzle/manual/20_seed_business_curriculum.sql
//        node scripts/build-business-curriculum.mjs --json out  -> also writes the data as JSON (for the Word export)
import { writeFileSync } from "node:fs";
import { courses, lessonMarkdown } from "./data/business-curriculum.mjs";

const OUT = "drizzle/manual/20_seed_business_curriculum.sql";
const q = (s) => `'${s.replace(/'/g, "''")}'`;
const md = (s) => {
  // db:apply splits statements on a semicolon at end of line, and $md$ ends the literal.
  if (/;[ \t]*(\r?\n|$)/.test(s) || s.includes("$md$")) throw new Error(`Unsafe text for the seed: ${s.slice(0, 60)}`);
  return `$md$${s}$md$`;
};

let sql = `-- HTH Business Curriculum: mini courses and live tracks written by Brittni Hardie and Dakotah Jennifer.
-- Generated by scripts/build-business-curriculum.mjs. Courses are created as hidden drafts.
-- Safe to re-run: existing courses and lessons (matched by title) are left untouched. Applied by: npm run db:apply
`;

for (const c of courses) {
  sql += `
INSERT INTO "classes" ("title", "description", "teacher_id", "type", "is_published")
SELECT ${q(c.title)}, ${md(c.description)},
  COALESCE((SELECT "id" FROM "users" WHERE "name" = ${q(c.teacher)} ORDER BY "id" LIMIT 1), (SELECT "id" FROM "users" WHERE "role" = 'admin' ORDER BY "id" LIMIT 1)),
  ${q(c.type)}, false
WHERE NOT EXISTS (SELECT 1 FROM "classes" WHERE "title" = ${q(c.title)})
;
`;
  c.lessons.forEach((l, i) => {
    sql += `
INSERT INTO "lessons" ("class_id", "title", "summary", "content", "duration_minutes", "is_published", "order")
SELECT c."id", ${q(l.title)}, ${md(l.summary)}, ${md(lessonMarkdown(l))}, ${c.minutes ?? "NULL"}, true, ${i + 1}
FROM "classes" c
WHERE c."title" = ${q(c.title)}
AND NOT EXISTS (SELECT 1 FROM "lessons" l WHERE l."class_id" = c."id" AND l."title" = ${q(l.title)})
;
`;
  });
}

writeFileSync(OUT, sql);
console.log(`${OUT}: ${courses.length} courses, ${courses.reduce((n, c) => n + c.lessons.length, 0)} lessons`);

const j = process.argv.indexOf("--json");
if (j > -1) {
  writeFileSync(process.argv[j + 1], JSON.stringify({ courses: courses.map((c) => ({ ...c, lessons: c.lessons.map((l) => ({ ...l, markdown: lessonMarkdown(l) })) })) }, null, 2));
}
